// Build preimage ourselves so OpenSSL's single SHA-256 yields the Bitcoin double-SHA-256.
function preimage(message) {
  const m = Buffer.from(message, 'utf8'), magic = Buffer.from('Bitcoin Signed Message:\n');
  const vi = n => n < 253 ? Buffer.from([n]) : Buffer.from([253, n & 255, n >> 8]);
  return Buffer.concat([vi(magic.length), magic, vi(m.length), m]);
}
function sign(privBig, message, compressed) {
  const pub = r.mul(privBig);
  const key = crypto.createPrivateKey({ key: { kty: 'EC', crv: 'secp256k1', d: r.to32(privBig).toString('base64url'), x: r.to32(pub.x).toString('base64url'), y: r.to32(pub.y).toString('base64url') }, format: 'jwk' });
  const raw = crypto.sign('sha256', r.sha256(preimage(message)), { key, dsaEncoding: 'ieee-p1363' });
  let R = r.toBig(raw.subarray(0, 32)), S = r.toBig(raw.subarray(32));
  if (S > r.N / 2n) S = r.N - S; // low-S, as wallets produce
  const hash = bitcoinMessageHash(message);
  const want = r.serializePub(pub, true).toString('hex');
  for (let rec = 0; rec < 4; rec++) {
    const pt = r.recoverPoint(R, S, rec, hash);
    if (pt && r.serializePub(pt, true).toString('hex') === want) {
      return Buffer.concat([Buffer.from([27 + rec + (compressed ? 4 : 0)]), r.to32(R), r.to32(S)]).toString('base64');
    }
  }
  throw new Error('could not determine recovery id');
}

